-- Notifications generated for likes and comments on a member's own posts.
CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  actor_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  post_id uuid NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('like','comment')),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz
);

CREATE INDEX IF NOT EXISTS notifications_recipient_created_idx
  ON public.notifications(recipient_id, created_at DESC);

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can read their notifications" ON public.notifications;
CREATE POLICY "Users can read their notifications"
  ON public.notifications FOR SELECT TO authenticated
  USING (recipient_id = auth.uid());

DROP POLICY IF EXISTS "Users can mark their notifications read" ON public.notifications;
CREATE POLICY "Users can mark their notifications read"
  ON public.notifications FOR UPDATE TO authenticated
  USING (recipient_id = auth.uid())
  WITH CHECK (recipient_id = auth.uid());

-- Restrict client updates to the read_at column only.
REVOKE UPDATE ON public.notifications FROM authenticated;
GRANT UPDATE (read_at) ON public.notifications TO authenticated;

-- No client INSERT policy: only trusted database triggers create notifications.
CREATE OR REPLACE FUNCTION public.reag_notify_post_owner()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  post_owner uuid;
  actor uuid;
BEGIN
  actor := NEW.user_id;
  SELECT user_id INTO post_owner FROM public.posts WHERE id = NEW.post_id;
  IF post_owner IS NOT NULL AND post_owner <> actor THEN
    INSERT INTO public.notifications(recipient_id, actor_id, post_id, kind)
    VALUES (post_owner, actor, NEW.post_id,
      CASE WHEN TG_TABLE_NAME = 'likes' THEN 'like' ELSE 'comment' END);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reag_notify_like ON public.likes;
CREATE TRIGGER reag_notify_like
AFTER INSERT ON public.likes
FOR EACH ROW EXECUTE FUNCTION public.reag_notify_post_owner();

DROP TRIGGER IF EXISTS reag_notify_comment ON public.comments;
CREATE TRIGGER reag_notify_comment
AFTER INSERT ON public.comments
FOR EACH ROW EXECUTE FUNCTION public.reag_notify_post_owner();

